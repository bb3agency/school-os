"""The Windows installer's sources (D69, ADR-0032 §7): the WiX v4 package, the WinSW service
configuration, the pinned downloads and the build script. The MSI itself is built and signed only
by the release workflow on a Windows runner (job ``edge-agent-msi``)."""

from __future__ import annotations

import hashlib
import re
import struct
import tomllib
from pathlib import Path
from xml.etree.ElementTree import Element

import pytest
from defusedxml import ElementTree as SafeET  # type: ignore[import-untyped]

AGENT = Path(__file__).resolve().parents[1]
INSTALLER = AGENT / "installer"
WXS = INSTALLER / "SchoolOSTallyAgent.wxs"
PINS = INSTALLER / "pins.toml"
BUILD = INSTALLER / "build.ps1"
SERVICE_XML = AGENT / "windows" / "sos-tally-agent.xml"
NS = {"w": "http://wixtoolset.org/schemas/v4/wxs", "u": "http://wixtoolset.org/schemas/v4/wxs/util"}
SERVICE = "SchoolOSTallyAgent"
HEX64 = re.compile(r"^[0-9a-f]{64}$")


def _service_sid(name: str) -> str:
    """The SID of ``NT SERVICE\\<name>``: S-1-5-80- and the SHA-1 of the upper-case UTF-16 name
    as five little-endian 32-bit numbers."""
    digest = hashlib.sha1(name.upper().encode("utf-16-le")).digest()  # noqa: S324 - Windows' rule
    return "S-1-5-80-" + "-".join(str(part) for part in struct.unpack("<5I", digest))


def _wxs() -> Element:
    root: Element = SafeET.parse(WXS).getroot()
    return root


def _one(root: Element, path: str) -> Element:
    found = root.findall(path, NS)
    assert len(found) == 1, path
    return found[0]


def test_D69_service_sid_rule_matches_a_known_windows_sid() -> None:
    assert _service_sid("TrustedInstaller") == (
        "S-1-5-80-956008885-3418522649-1831038044-1853292631-2271478464"
    )


def test_D69_package_is_per_machine_with_a_stable_upgrade_code_and_major_upgrade() -> None:
    package = _one(_wxs(), "w:Package")
    assert package.get("Scope") == "perMachine"
    assert package.get("Version") == "$(var.ProductVersion)"
    # The UpgradeCode never changes: a new value would install a second copy beside the old one.
    assert package.get("UpgradeCode") == "{53A0FDBB-BDDA-4B4B-9A2F-D9D6AE3E85EA}"
    assert _one(package, "w:MajorUpgrade").get("DowngradeErrorMessage")
    program_files = _one(package, "w:StandardDirectory[@Id='ProgramFiles64Folder']")
    assert [d.get("Name") for d in program_files.iter(f"{{{NS['w']}}}Directory")] == [
        "SchoolOS",
        "TallyAgent",
        "python",
    ]
    components = list(_wxs().iter(f"{{{NS['w']}}}Component"))
    assert components
    assert all(c.get("Bitness") == "always64" for c in components)


def test_D69_package_references_exactly_the_files_build_ps1_stages() -> None:
    sources = sorted(f.get("Source", "") for f in _wxs().iter(f"{{{NS['w']}}}File"))
    assert sources == [
        r"!(bindpath.stage)\sos-tally-agent.exe",
        r"!(bindpath.stage)\sos-tally-agent.xml",
        r"!(bindpath.stage)\tally-agent.cmd",
    ]
    script = BUILD.read_text(encoding="utf-8")
    for name in ("sos-tally-agent.exe", "sos-tally-agent.xml", "tally-agent.cmd"):
        assert f"Join-Path $stage '{name}'" in script, name
    # The python\ payload is generated by build.ps1 into the component group the feature uses.
    feature = _one(_wxs(), "w:Package/w:Feature")
    groups = {g.get("Id") for g in feature.findall("w:ComponentGroupRef", NS)}
    assert groups == {"AgentService", "PythonRuntime"}
    assert '<ComponentGroup Id="PythonRuntime" Directory="PYTHONDIR">' in script
    assert "!(bindpath.stage)\\python\\" in script
    assert "'-bindpath', \"stage=$stage\"" in script
    assert "ProductVersion=$ProductVersion" in script
    assert (INSTALLER / "tally-agent.cmd").is_file()
    assert SERVICE_XML.is_file()


def test_D69_service_runs_as_its_virtual_account_never_local_system() -> None:
    install = _one(_wxs(), ".//w:ServiceInstall")
    assert install.get("Name") == SERVICE
    assert install.get("Account") == f"NT SERVICE\\{SERVICE}"
    assert install.get("Password") is None  # virtual accounts have none
    values = " ".join(v.lower() for e in _wxs().iter() for v in e.attrib.values())
    for forbidden in ("localsystem", "nt authority\\system", "localservice", "networkservice"):
        assert forbidden not in values
    service = SafeET.parse(SERVICE_XML).getroot()
    assert service.findtext("id") == SERVICE  # WinSW's id is the MSI's service name
    assert service.find("serviceaccount") is None  # the MSI sets the account, not WinSW


def test_D69_service_starts_delayed_automatic_and_restarts_on_failure() -> None:
    install = _one(_wxs(), ".//w:ServiceInstall")
    assert install.get("Start") == "auto"
    assert _one(install, "w:ServiceConfig").get("DelayedAutoStart") == "yes"
    failure = _one(install, "u:ServiceConfig")
    for action in ("First", "Second", "Third"):
        assert failure.get(f"{action}FailureActionType") == "restart"
    assert int(failure.get("RestartServiceDelayInSeconds", "0")) >= 60
    control = _one(_wxs(), ".//w:ServiceControl")
    # Uninstall stops and removes the service.
    assert (control.get("Name"), control.get("Stop"), control.get("Remove")) == (
        SERVICE,
        "both",
        "uninstall",
    )


def test_D69_program_data_acl_grants_only_the_service_account_and_administrators() -> None:
    component = _one(_wxs(), ".//w:Component[@Id='StateFolder']")
    assert component.get("Directory") == "STATEFOLDER"
    assert component.get("Permanent") == "yes"  # uninstall leaves configuration and key
    data = _one(_wxs(), "w:Package/w:StandardDirectory[@Id='CommonAppDataFolder']")
    assert [d.get("Name") for d in data.iter(f"{{{NS['w']}}}Directory")] == [
        "SchoolOS",
        "TallyAgent",
    ]
    sddl = _one(component, "w:CreateFolder/w:PermissionEx").get("Sddl", "")
    dacl = sddl.split("D:", 1)[1]
    assert dacl.startswith("PAI("), "protected DACL: nothing inherited from ProgramData"
    aces = re.findall(r"\(([^)]*)\)", dacl)
    trustees = {ace.split(";")[5]: ace for ace in aces}
    assert set(trustees) == {"BA", _service_sid(SERVICE)}
    assert all(ace.startswith("A;") for ace in aces)  # allow entries only, no extra rights
    assert len(component.findall("w:CreateFolder/w:Permission", NS)) == 0


def test_D69_service_and_admin_command_use_the_program_data_state_folder() -> None:
    service = SafeET.parse(SERVICE_XML).getroot()
    state = r"%ProgramData%\SchoolOS\TallyAgent"
    assert service.findtext("executable") == r"%BASE%\python\python.exe"
    arguments = service.findtext("arguments") or ""
    assert arguments.startswith("-I -m sos_edge_agent.cli")
    assert f'--state-dir "{state}" run' in arguments
    assert (service.findtext("logpath") or "").startswith(state)
    command = (INSTALLER / "tally-agent.cmd").read_text(encoding="utf-8")
    assert f'--state-dir "{state}"' in command


def test_D69_no_auto_update() -> None:
    text = "\n".join(p.read_text(encoding="utf-8").lower() for p in (WXS, SERVICE_XML, BUILD, PINS))
    for word in ("<download", "autoupdate", "auto-update>", "scheduledtask", "schtasks"):
        assert word not in text


def test_D69_pins_have_a_version_url_and_sha256_for_each_download() -> None:
    pins = tomllib.loads(PINS.read_text(encoding="utf-8"))
    assert set(pins) == {"python", "winsw", "wix"}
    assert re.fullmatch(r"3\.12\.\d+", pins["python"]["version"])  # the agent needs 3.12
    assert re.fullmatch(r"4\.\d+\.\d+", pins["wix"]["version"])  # WiX v4
    for name in ("python", "winsw"):
        pin = pins[name]
        assert set(pin) >= {"version", "file", "url", "sha256"}, name
        assert pin["url"].startswith("https://"), name
        assert pin["version"] in pin["url"], name
        assert pin["url"].endswith("/" + pin["file"]), name
        # Either a real SHA-256 or a placeholder that build.ps1 refuses (the next test).
        assert HEX64.match(pin["sha256"]) or pin["sha256"].startswith("REPLACE-"), name


def test_D69_build_refuses_placeholder_hashes_and_checks_every_download() -> None:
    script = BUILD.read_text(encoding="utf-8")
    assert "if ($pin['sha256'] -notmatch '^[0-9a-f]{64}$')" in script
    assert "Get-FileHash -LiteralPath $target -Algorithm SHA256" in script
    assert "if ($actual -ne $Pin['sha256'])" in script
    assert "$python = Get-Pin $pins 'python'" in script
    assert "$winsw = Get-Pin $pins 'winsw'" in script
    # Locked dependencies only, hashes required, binary wheels for CPython 3.12 on x64 Windows.
    assert "'--frozen'" in script
    assert "'--require-hashes'" in script
    assert "'--only-binary', ':all:'" in script
    assert "'x86_64-pc-windows-msvc'" in script


@pytest.mark.parametrize(
    "construct",
    [
        "??",  # null-coalescing (PowerShell 7)
        "?.",  # null-conditional member access (PowerShell 7)
        "-Parallel",
        "&&",  # pipeline chain operators (PowerShell 7)
        "||",
        "Join-Path -AdditionalChildPath",
    ],
)
def test_D69_build_script_stays_windows_powershell_5_1_compatible(construct: str) -> None:
    lines = BUILD.read_text(encoding="utf-8").splitlines()
    code = "\n".join(line for line in lines if not line.strip().startswith("#"))
    assert construct not in code
