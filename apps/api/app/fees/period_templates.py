"""A4 print page of the collection register (FM-04; FR-FEE-062; CLAUDE.md §10 "print is
first-class").

Pure module: the service passes finished display strings and gets a self-contained page back.
Every value is escaped and Aadhaar-masked. The page uses exactly ``templates.REPORT_STYLE``, so
the route's ``STYLE_CSP`` allows it by hash; no scripts, links or images. English (ADR-0036).
"""

from __future__ import annotations

import html
from collections.abc import Sequence

from app.core.redaction import mask_aadhaar
from app.fees.templates import REPORT_STYLE


def _e(value: object) -> str:
    text = "" if value is None else str(value)
    return html.escape(mask_aadhaar(text), quote=True)


def _table(head: Sequence[str], rows: Sequence[Sequence[str]], num: set[int]) -> str:
    if not rows:
        return "<p>None.</p>"
    th = "".join(
        f'<th class="num">{_e(h)}</th>' if i in num else f"<th>{_e(h)}</th>"
        for i, h in enumerate(head)
    )
    body = "".join(
        "<tr>"
        + "".join(
            f'<td class="num">{_e(v)}</td>' if i in num else f"<td>{_e(v)}</td>"
            for i, v in enumerate(r)
        )
        + "</tr>"
        for r in rows
    )
    return f"<table><thead><tr>{th}</tr></thead><tbody>{body}</tbody></table>"


def render_collection_register(
    *,
    school_name: str,
    period: str,
    totals: Sequence[tuple[str, str]],
    by_day: Sequence[Sequence[str]],
    by_head: Sequence[Sequence[str]],
    by_mode: Sequence[Sequence[str]],
    by_collector: Sequence[Sequence[str]],
    cancellations: Sequence[Sequence[str]],
    refunds: Sequence[Sequence[str]],
    receipts_note: str,
) -> str:
    """The collection register of a period on A4 (FR-FEE-062). Rows arrive as display strings;
    the receipt list itself is in the download (a year of receipts does not belong on paper)."""
    total_rows = "".join(
        f'<tr class="totals"><td>{_e(k)}</td><td class="num">{_e(v)}</td></tr>' for k, v in totals
    )
    money = ["Gross (₹)", "Cancelled (₹)", "Refunded (₹)", "Net (₹)"]
    body = (
        f'<main><p class="school">{_e(school_name)}</p>'
        f"<h1>Collection register · {_e(period)}</h1>"
        f"<p>{_e(receipts_note)}</p>"
        "<h2>Totals</h2>"
        f"<table><tbody>{total_rows}</tbody></table>"
        "<h2>By head</h2>"
        + _table(
            ["Head", "Collected (₹)", "Cancelled (₹)", "Refunded (₹)", "Net (₹)"],
            by_head,
            {1, 2, 3, 4},
        )
        + "<h2>By mode</h2>"
        + _table(["Mode", "Receipts", *money], by_mode, {1, 2, 3, 4, 5})
        + "<h2>By collector</h2>"
        + _table(["Collected by", "Receipts", "Gross (₹)"], by_collector, {1, 2})
        + "<h2>By day</h2>"
        + _table(["Date", "Receipts", *money], by_day, {1, 2, 3, 4, 5})
        + "<h2>Cancelled receipts (approved in the period)</h2>"
        + _table(
            ["Receipt", "Receipt date", "Cancelled on", "Reason", "Amount (₹)"],
            cancellations,
            {4},
        )
        + "<h2>Refunds paid in the period</h2>"
        + _table(["Voucher", "Date", "Receipt", "Mode", "Amount (₹)"], refunds, {4})
        + '<div class="signatures"><div>Accountant</div><div>Principal</div>'
        "<div>Correspondent</div></div>"
        "<footer>Generated by SchoolOS · personal financial data: keep it in the office"
        "</footer></main>"
    )
    return (
        "<!doctype html>"
        '<html lang="en"><head><meta charset="utf-8">'
        '<meta name="viewport" content="width=device-width, initial-scale=1">'
        '<meta name="robots" content="noindex, nofollow">'
        f"<title>{_e('Collection register ' + period)}</title><style>{REPORT_STYLE}</style>"
        f"</head><body>{body}</body></html>"
    )


__all__ = ["render_collection_register"]
