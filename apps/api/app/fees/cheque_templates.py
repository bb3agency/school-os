"""A4 print page of the cheque deposit list (FM-08; FR-FEE-136; CLAUDE.md §10 "print is
first-class").

Pure module: the service passes finished display strings and gets a self-contained page back.
Every value is escaped and Aadhaar-masked. The page uses exactly ``templates.REPORT_STYLE``, so
the route's ``STYLE_CSP`` allows it by hash; no scripts, links or images. English (ADR-0036).
"""

from __future__ import annotations

import html
from collections.abc import Sequence

from app.core.redaction import mask_aadhaar
from app.fees.templates import REPORT_STYLE


def _e(value: object) -> str:
    text = "" if value is None else str(value)
    return html.escape(mask_aadhaar(text), quote=True)


def render_deposit_slip(
    *,
    school_name: str,
    day: str,
    rows: Sequence[Sequence[str]],
    total: str,
    count: int,
) -> str:
    """Cheques marked deposited on one day: serial, cheque number, drawee bank, cheque date,
    receipt number and amount, with the total, for the bank's pay-in slip."""
    head = ["#", "Cheque no.", "Bank", "Cheque date", "Receipt", "Amount (₹)"]
    th = "".join(
        f'<th class="num">{_e(h)}</th>' if i == len(head) - 1 else f"<th>{_e(h)}</th>"
        for i, h in enumerate(head)
    )
    body_rows = "".join(
        "<tr>"
        + "".join(
            f'<td class="num">{_e(v)}</td>' if i == len(r) - 1 else f"<td>{_e(v)}</td>"
            for i, v in enumerate(r)
        )
        + "</tr>"
        for r in rows
    )
    table = (
        f"<table><thead><tr>{th}</tr></thead><tbody>{body_rows}"
        f'<tr class="totals"><td colspan="5">Total of {count} cheques</td>'
        f'<td class="num">{_e(total)}</td></tr></tbody></table>'
        if rows
        else "<p>No cheques were marked as deposited on this day.</p>"
    )
    body = (
        f'<main><p class="school">{_e(school_name)}</p>'
        f"<h1>Cheques deposited · {_e(day)}</h1>"
        f"{table}"
        '<div class="signatures"><div>Deposited by</div><div>Accountant</div>'
        "<div>Bank stamp</div></div>"
        "<footer>Generated by SchoolOS · keep with the bank's pay-in slip counterfoil</footer>"
        "</main>"
    )
    return (
        "<!doctype html>"
        '<html lang="en"><head><meta charset="utf-8">'
        '<meta name="viewport" content="width=device-width, initial-scale=1">'
        '<meta name="robots" content="noindex, nofollow">'
        f"<title>{_e('Cheques deposited ' + day)}</title><style>{REPORT_STYLE}</style>"
        f"</head><body>{body}</body></html>"
    )


__all__ = ["render_deposit_slip"]
