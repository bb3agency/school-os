def test_US_501_AC4_precheck_xlsx_and_pdf(school: Any, section: str, admin_engine: Engine) -> None:
    ready = EX.student(school, section_key=section, roll_no="2", name="Synthetica Ready Two")
    blocked = EX.student(school, section_key=section, roll_no="1", parents=False)
    warned = EX.student(
        school,
        section_key=section,
        roll_no="3",
        extra=[ValueIn(attribute_key="aadhaar_gender_as_printed", source=AAD, value="male")],
    )
    coordinator = school.people["exam_coordinator"]
    out = EX.request_precheck(school, coordinator, "exam_coordinator", section_keys=(section,))
    assert out.status == "queued"
    assert out.kind == "board_precheck"
    assert out.student_count == 3
    row = EX.export_row(admin_engine, out.id)
    assert sorted(row["student_ids"]) == sorted([ready, blocked, warned])
    assert EX.run(school, out.id) == "ready"

    row = EX.export_row(admin_engine, out.id)
    assert row["status"] == "ready"
    assert row["expires_at"] - row["finished_at"] == dt.timedelta(days=7)
    files = EX.files(admin_engine, out.id)
    assert [f["format"] for f in files] == ["pdf", "xlsx"]
    for f in files:
        assert f["object_key"].startswith(f"t/{school.tenant_id}/exports/{out.id}/")
    assert EX.stored(out.id, "pdf") == EX.PDF_BYTES

    wb = _xlsx(out.id)
    assert [ws.title for ws in wb.worksheets] == ["Summary", "Findings", "Ready to enter"]
    findings = _sheet(wb, 1)
    assert findings[0][0] == "Severity"
    severities = [r[0] for r in findings[1:]]
    assert severities[0] == "Blocker", "blockers first (US-501 AC2)"
    assert severities == sorted(
        severities, key=["Blocker", "High", "Medium", "Low", "Information"].index
    )
    rules = {r[4] for r in findings[1:]}
    assert {"DQ-005", "DQ-003"} <= rules
    ready_sheet = _sheet(wb, 2)
    assert ready_sheet[0] == [
        "Admission number",
        "Full name",
        "Gender",
        "Date of birth",
        "Father's name",
        "Mother's name",
        "Pre-check status",
    ]
    by_name = {r[1]: r for r in ready_sheet[1:]}
    assert by_name["Synthetica Ready Two"][2:4] == ["F", "14/03/2012"]
    statuses = [r[-1] for r in ready_sheet[1:]]
    # Unverified register values are low-severity warnings (DQ-005), so nobody is "Ready" yet.
    assert statuses == ["Blocked - fix first", "Check warnings", "Check warnings"], "by roll no"
    # The PDF was rendered from the escaped print page with the same findings.
    page = EX.FAKE.pages[-1]
    assert "Generated by SchoolOS for internal checking" in page
    assert "DQ-005" in page


