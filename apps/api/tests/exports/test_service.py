def test_portal_precheck_masks_c3_unless_included(
    school: Any, section: str, admin_engine: Engine
) -> None:
    EX.student(
        school,
        section_key=section,
        extra=[
            ValueIn(attribute_key="category", source="parent_form", value="obc"),
            ValueIn(attribute_key="mother_tongue", source="parent_form", value="Telugu"),
            ValueIn(attribute_key="aadhaar_last4", source=AAD, value="4821"),
            ValueIn(attribute_key="aadhaar_name_as_printed", source=AAD, value="Synthetica Aad"),
        ],
    )
    admin = school.people["office_admin"]
    masked = EX.request_precheck(
        school, admin, "office_admin", profile_key="udise-plus", section_keys=(section,)
    )
    assert masked.kind == "portal_precheck"
    EX.run(school, masked.id)
    ready = _sheet(_xlsx(masked.id), 2)
    header = ready[0]
    assert header[header.index("Social category")] == "Social category"
    assert ready[1][header.index("Social category")] == "••••"
    assert ready[1][header.index("Mother tongue")] == "Telugu"
    summary = _sheet(_xlsx(masked.id), 0)
    assert any("Restricted values are hidden" in str(r[1]) for r in summary)

    shown = EX.request_precheck(
        school,
        admin,
        "office_admin",
        profile_key="udise-plus",
        section_keys=(section,),
        include_sensitive=True,
    )
    EX.run(school, shown.id)
    ready = _sheet(_xlsx(shown.id), 2)
    assert ready[1][ready[0].index("Social category")] == "OBC"
    requested = EX.audit_rows(admin_engine, school.tenant_id, shown.id)[0]["summary"]
    assert requested["include_sensitive"] is True
    # ADR-0021 decision 2: the audit event names the restricted columns, never their values.
    assert requested["sensitive_columns"] == ["category"]
    assert "obc" not in str(requested).lower()
    unmasked = EX.audit_rows(admin_engine, school.tenant_id, masked.id)[0]["summary"]
    assert (unmasked["include_sensitive"], unmasked["sensitive_columns"]) == (False, [])
    # Aadhaar-as-printed values never appear in any file (PRV-013).
    for export_id in (masked.id, shown.id):
        for ws in _xlsx(export_id).worksheets:
            for row in ws.iter_rows():
                for cell in row:
                    assert "Synthetica Aad" not in str(cell.value or "")
    assert "Synthetica Aad" not in "".join(EX.FAKE.pages)


