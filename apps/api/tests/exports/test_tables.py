@settings(max_examples=200, deadline=None)
@given(st.from_regex(r"[2-9][0-9]{10}", fullmatch=True), st.sampled_from(["", " ", "-", "=", "@"]))
def test_invariant_4_property_verhoeff_numbers_never_survive(body: str, prefix: str) -> None:
    number = body + verhoeff_check_digit(body)
    assert number not in safe_cell(prefix + number)
    assert number not in clean_text(number)


def test_control_characters_are_removed_but_line_breaks_kept() -> None:
    assert clean_text("A\x00B\x07C\nD") == "ABC\nD"


def test_xlsx_watermark_in_print_header_and_telugu_kept() -> None:
    table = Table(name="సారాంశం", header=("పూర్తి పేరు",), rows=(("వెంకట సాయి",),))
    wb = load_workbook(io.BytesIO(write_xlsx([table], watermark=WATERMARK, title="t")))
    ws = wb.worksheets[0]
    assert ws.title == "సారాంశం"
    assert ws["A2"].value == "వెంకట సాయి"
    header = ws.oddHeader
    assert header is not None
    assert "Generated by SchoolOS for internal checking" in (header.center.text or "")
    assert ws.freeze_panes == "A2"


def test_sheet_titles_are_valid_and_unique() -> None:
    used: set[str] = set()
    a = sheet_title("Ready to enter: 9A/9B [x]", used)
    b = sheet_title("Ready to enter: 9A/9B [x]", used)
    assert a != b
    for title in (a, b):
        assert len(title) <= 31
        assert not set(title) & set("[]:*?/\\")


