"""Safe cells and writers: formula injection (SEC-017) and Aadhaar masking in every exported
cell (invariant 4, PRV-013, PRV-015); watermark (FR-EXP-003, US-901 AC2)."""

from __future__ import annotations

import csv
import io
import zipfile

import pytest
from hypothesis import given, settings
from hypothesis import strategies as st
from openpyxl import load_workbook

from app.core.redaction import contains_full_aadhaar, verhoeff_check_digit
from app.exports.tables import (
    FORMULA_TRIGGERS,
    Table,
    clean_text,
    safe_cell,
    sheet_title,
    write_csv,
    write_xlsx,
)

WATERMARK = "Generated by SchoolOS for internal checking · అంతర్గత తనిఖీ కోసం SchoolOS రూపొందించింది"
INJECTIONS = [
    '=HYPERLINK("http://evil.test","click")',
    "=1+2",
    "+SUM(A1:A2)",
    "-2+3",
    "@SUM(A1)",
    "\t=1+1",
    "\r=1+1",
    "=cmd|' /C calc'!A0",
]


def _aadhaar() -> str:
    body = "23456789012"
    return body + verhoeff_check_digit(body)


def _csv_rows(data: bytes) -> list[list[str]]:
    text = data.decode("utf-8")
    assert text.startswith("﻿"), "BOM so Excel reads Telugu"
    return list(csv.reader(io.StringIO(text[1:])))


@pytest.mark.parametrize("value", INJECTIONS)
def test_SEC_017_formula_triggers_are_prefixed(value: str) -> None:
    out = safe_cell(value)
    assert out.startswith("'")
    assert out[1:] == value.replace("\x00", "")


@pytest.mark.parametrize("value", ["Venkata Sai", "K. Lakshmi", "9A", "", "2012-03-14"])
def test_SEC_017_ordinary_values_are_unchanged(value: str) -> None:
    assert safe_cell(value) == value


def test_SEC_017_none_is_an_empty_cell() -> None:
    assert safe_cell(None) == ""


def test_SEC_017_csv_cells_are_neutralised() -> None:
    table = Table(name="Students", header=("=H1", "Name"), rows=tuple((v, v) for v in INJECTIONS))
    rows = _csv_rows(write_csv(table, watermark=WATERMARK))
    assert rows[0] == [WATERMARK]
    assert rows[1][0] == "'=H1"
    for row in rows[2:]:
        for cell in row:
            assert cell.startswith("'"), cell
            assert not cell.startswith(FORMULA_TRIGGERS)


def test_SEC_017_xlsx_cells_are_text_never_formulas() -> None:
    table = Table(
        name="Findings", header=("Value", "@header"), rows=tuple((v, v) for v in INJECTIONS)
    )
    data = write_xlsx([table], watermark=WATERMARK, title="=title")
    wb = load_workbook(io.BytesIO(data))
    ws = wb["Findings"]
    assert ws["B1"].value == "'@header"
    for row in ws.iter_rows(min_row=2):
        for cell in row:
            assert cell.data_type == "s", (cell.coordinate, cell.data_type)
            assert isinstance(cell.value, str)
            assert cell.value.startswith("'")
    # The raw sheet XML holds no formula element at all.
    with zipfile.ZipFile(io.BytesIO(data)) as z:
        sheet_xml = z.read("xl/worksheets/sheet1.xml").decode()
    assert "<f>" not in sheet_xml
    assert "<f " not in sheet_xml
    assert wb.properties.title == "'=title"


def test_invariant_4_aadhaar_masked_in_every_cell_csv_and_xlsx() -> None:
    number = _aadhaar()
    spaced = f"{number[:4]} {number[4:8]} {number[8:]}"
    values = (number, f"ID {spaced} noted", f"={number}")
    table = Table(name="S", header=(f"Header {number}", "b", "c"), rows=(values,))
    csv_text = write_csv(table, watermark=f"{WATERMARK} {number}").decode()
    assert number not in csv_text
    assert not contains_full_aadhaar(csv_text)
    assert "XXXX XXXX " + number[-4:] in csv_text
    wb = load_workbook(io.BytesIO(write_xlsx([table], watermark=WATERMARK, title=number)))
    for ws in wb.worksheets:
        for row in ws.iter_rows():
            for cell in row:
                assert not contains_full_aadhaar(str(cell.value or "")), cell.coordinate
    assert not contains_full_aadhaar(wb.properties.title or "")


